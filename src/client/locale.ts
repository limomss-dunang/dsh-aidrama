export type LocaleId = 'zh-CN' | 'en-US'

let current: LocaleId = 'zh-CN'

export function applyLocale(id: string): void {
  current = id.toLowerCase().startsWith('en') ? 'en-US' : 'zh-CN'
}

export function getLocale(): LocaleId {
  return current
}

